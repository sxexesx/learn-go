package main

import "fmt"

func main() {
	s1 := make([]int, 3, 5) // len = 3; cap = 5; s1 = [0,0,0],0,0
	s2 := s1[:2]            // len = 2; cap = 5; s2 = [0,0],0,0,0;

	s1[0] = 1 // s1 = [1,0,0],0,0
	s2[1] = 2 // s2 = [1,2],0,0,0; s1 = [1,2,0],0,0

	modify(s1, 55)
	// s1 = [999,2,0],55,0, s2 = [999,2],0,55,0
	modify(s2, 66)
	// s1 = [999,2,55],66,0, s2 = [99,2],66,55,0

	fmt.Println("s1:", s1)                                  // [999,2,0]
	fmt.Println("s2:", s2)                                  // [999,2]
	fmt.Println("s1 cap = ", cap(s1), "s2 cap = ", cap(s2)) // 5 5
}

func modify(s []int, n int) {
	s = append(s, n)
	// len = 4; cap = 5; s = [1,2,0,55],0 copy of s1 = [1,2,0],55,0
	s[0] = 999
	// s = [999,2,0,55],0 copy of s1 = [999,2,0],55,0

	// s1 = [999,2,0],55,0, s2 = [999,2],0,55,0
	// len 4; cap 5; s = [999,2,66,55],0; s1 = [999,2,66,55],0; s2 = [999,2],66,55,0

}
